// Run with node tests/test_reliability_ui.cjs; exercises the shipped renderer.
const fs = require('fs'), vm = require('vm'), assert = require('assert');
const html = fs.readFileSync(require('path').join(__dirname,'../workshop/course.html'),'utf8');
const ids = new Set([...html.matchAll(/id="([^"]+)"/g)].map(m=>m[1]));
const nodes = new Map();
const el = id => {
  assert(ids.has(id), 'missing DOM element '+id);
  if (!nodes.has(id)) nodes.set(id,{classList:{toggle(){}},textContent:'',innerHTML:''});
  return nodes.get(id);
};
const ctx = vm.createContext({el,pendingPost:false});
vm.runInContext(html.slice(html.indexOf('function renderReliability(s)'),html.indexOf('function plot(arena)')),ctx);
const s={mode:'PHYSICAL',connected:true,calibration:null,course:{},active_job:null};
ctx.renderReliability(s);
assert(el('rel-baseline').disabled);
assert(!el('reliabilityPrerequisite').hidden);
assert(el('reliabilityTitle').textContent.includes('真机实测'));
assert(el('reliabilitySource').textContent.includes('直接采集 AS7341'));
s.calibration={id:'a'};
ctx.renderReliability(s);
assert(!el('rel-baseline').disabled);
assert(el('rel-drift').disabled);
assert(el('reliabilityHelp').textContent.includes('取出色片'));
const stage={status:'completed',rows:[{raw:[100,200,300,400,500,600,700,800]}],mean_raw:[100,200,300,400,500,600,700,800],passed:true,rms_relative:0};
s.course.reliability={mode:'PHYSICAL',calibration_id:'a',color_filter:'red',stages:{baseline:stage}};
ctx.renderReliability(s);
assert(!el('rel-drift').disabled);
assert(el('reliabilityHelp').textContent.includes('放稳后'));
s.course.reliability.stages.drift=stage;
ctx.renderReliability(s);
assert(!el('rel-recovery').disabled);
assert(el('reliabilityHelp').textContent.includes('手动移除'));
ctx.pendingPost=true;
ctx.renderReliability(s);
assert(el('rel-baseline').disabled && el('rel-drift').disabled && el('rel-recovery').disabled);
ctx.pendingPost=false;
s.connected=false;
ctx.renderReliability(s);
assert(el('rel-baseline').disabled && el('rel-recovery').disabled);
s.connected=true;
s.mode='SIMULATED';
ctx.renderReliability(s);
assert(el('reliabilitySource').textContent.includes('教学示意'));
assert(el('rel-drift').disabled); // cannot continue results from the other mode
assert(!el('reliabilitySpectrum').innerHTML.includes('<svg'));
s.course.reliability.mode='SIMULATED';
ctx.renderReliability(s);
assert(!el('rel-drift').disabled);
s.calibration.id='b';
ctx.renderReliability(s);
assert(el('rel-drift').disabled);
console.log('PASS: physical/simulated labels, prerequisites, ordered stages, busy/disconnect and stale-result isolation');
ctx.document={querySelectorAll(){return [];}};
ctx.state={mode:'PHYSICAL',connected:true,capabilities:{physical_benchmark:true},active_job:null,calibration:{id:'x'},course:{stability:{passed:true,calibration_id:'x'},fault:'none'},arena:{round_id:'r',ai_runs:{}}};
el('seeds').value='1,2';el('budgets').value='6,8';
vm.runInContext(html.slice(html.indexOf('function parseIntList('),html.indexOf('async function startBenchmark(')),ctx);
vm.runInContext(html.slice(html.indexOf('function syncBusyButtons('),html.indexOf('function parseIntList(')),ctx);
ctx.syncBusyButtons();
assert(!el('btnBenchmark').disabled);
assert(el('benchmarkCount').textContent.includes('32 次真实测量'));
ctx.state.active_job='physical_benchmark';ctx.syncBusyButtons();assert(el('btnBenchmark').disabled);
ctx.state.active_job=null;ctx.state.capabilities={};ctx.syncBusyButtons();assert(el('btnBenchmark').disabled);
ctx.state.capabilities.physical_benchmark=true;
el('seeds').value='1,1';ctx.syncBusyButtons();assert(el('btnBenchmark').disabled);
el('seeds').value='1,2';ctx.state.arena.round_id=null;ctx.syncBusyButtons();assert(el('btnBenchmark').disabled);
assert(!html.includes('去任务 6：色片对照'));
console.log('PASS: physical benchmark availability, count, prerequisites, invalid inputs and ordered navigation');
